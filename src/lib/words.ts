function build(): string[] {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const w of RAW.split(/\s+/)) {
    if (!w) continue;
    const c = canonicalize(w);
    if (seen.has(c)) continue;
    seen.add(c);
    out.push(c);
  }
  return out;
}

export const WORDS: readonly string[] = build();

export function randomWords(count: number, avoid?: string): string[] {
  const out: string[] = [];
  let last = avoid;
  for (let i = 0; i < count; i++) {
    let w: string;
    do {
      w = WORDS[Math.floor(Math.random() * WORDS.length)];
    } while (w === last && WORDS.length > 1);
    out.push(w);
    last = w;
  }
  return out;
}
